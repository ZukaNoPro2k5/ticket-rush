export const categoryLabel = (locale: Locale, category: EventCategory) =>
  messages[locale].categories[category];

export const formatCurrency = (locale: Locale, value: number) =>
  new Intl.NumberFormat(localeTag(locale), {
    style: 'currency',
    currency: 'VND',
    maximumFractionDigits: 0,
  }).format(value);
